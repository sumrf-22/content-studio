"""Local model-provider settings and BYOK key storage.

Providers live in ``<data>/settings/providers.json``. API keys are encrypted
with Fernet using ``CONTENT_STUDIO_SECRET_KEY``; only the last four characters
are kept in plain text so the UI can show a masked hint. The raw key is never
written to disk, returned by the API, or included in an error message.
"""

import json
import os
import sys
import tempfile
import uuid
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

from cryptography.fernet import Fernet, InvalidToken

import core.state as state_module
import config as config_module

SECRET_ENV = "CONTENT_STUDIO_SECRET_KEY"
LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}
PROVIDER_FILE_NAME = "providers.json"

# Retained as a module-level path so tests can point the writer at a throwaway
# file. Production always uses the repository ``.env``.
ENV_FILE = config_module.ENV_FILE


class SettingsError(ValueError):
    """A validation, storage, or key-configuration problem."""


def _settings_dir():
    return state_module.DATA / "settings"


def providers_path():
    return _settings_dir() / PROVIDER_FILE_NAME


def _now():
    return datetime.now(timezone.utc).isoformat()


# ---------------------------------------------------------------------------
# Secret key handling
# ---------------------------------------------------------------------------


def _is_fernet_key(value):
    try:
        Fernet(value.encode("ascii"))
    except (ValueError, TypeError, UnicodeEncodeError):
        return False
    return True


def _write_secret_to_env(key):
    path = Path(ENV_FILE)
    path.parent.mkdir(parents=True, exist_ok=True)

    existing = ""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if SECRET_ENV in existing:
            return

    with path.open("a", encoding="utf-8") as handle:
        if existing and not existing.endswith("\n"):
            handle.write("\n")
        handle.write(
            "# Generated by Content Studio on first provider save. "
            "Keep this file private; never commit it.\n"
        )
        handle.write(f"{SECRET_ENV}={key}\n")

    print(
        "Content Studio: generated CONTENT_STUDIO_SECRET_KEY and wrote it to "
        f"{path}. Keep this file private.",
        file=sys.stderr,
    )


def ensure_secret_key(create=True):
    """Return the Fernet key, generating and persisting one on first save.

    ``create=False`` is used for decryption: if the key is gone we must not
    silently rotate it, because that would make stored keys unreadable.
    """
    key = os.environ.get(SECRET_ENV, "").strip()
    if key:
        if not _is_fernet_key(key):
            raise SettingsError(
                f"{SECRET_ENV} is not a valid Fernet key. Fix or remove it "
                "before adding providers."
            )
        return key

    if not create:
        raise SettingsError(
            f"{SECRET_ENV} is missing, so saved API keys cannot be decrypted. "
            "Restore the key in .env or re-enter the provider key."
        )

    key = Fernet.generate_key().decode("ascii")
    _write_secret_to_env(key)
    os.environ[SECRET_ENV] = key
    return key


def encrypt_key(raw_key):
    return Fernet(ensure_secret_key(create=True)).encrypt(
        raw_key.encode("utf-8")
    ).decode("ascii")


def decrypt_key(token):
    if not token:
        raise SettingsError("provider has no API key")
    try:
        return (
            Fernet(ensure_secret_key(create=False))
            .decrypt(token.encode("ascii"))
            .decode("utf-8")
        )
    except InvalidToken as exc:
        raise SettingsError(
            "saved API key cannot be decrypted with the current "
            f"{SECRET_ENV}. Re-enter the key for this provider."
        ) from exc


def masked_key(provider):
    """Return a display hint built from a static prefix and the stored last 4."""
    last4 = str(provider.get("api_key_last4") or "")
    if not last4:
        return ""
    host = (urlparse(str(provider.get("base_url") or "")).hostname or "").lower()
    if host == "openrouter.ai":
        return f"sk-or-...{last4}"
    if host.endswith("sensenova.cn"):
        return f"sk-...{last4}"
    return f"...{last4}"


# ---------------------------------------------------------------------------
# Provider file
# ---------------------------------------------------------------------------


def _empty_store():
    return {"version": 1, "providers": []}


def _load():
    path = providers_path()
    if not path.exists():
        return _empty_store()

    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError, ValueError) as exc:
        raise SettingsError(
            "providers.json is unreadable; fix or remove it before editing "
            "providers."
        ) from exc

    if not isinstance(data, dict) or not isinstance(data.get("providers"), list):
        raise SettingsError("providers.json has an unexpected shape.")
    return data


def _save(store):
    directory = _settings_dir()
    directory.mkdir(parents=True, exist_ok=True)
    path = providers_path()

    fd, tmp_path = tempfile.mkstemp(
        dir=directory, prefix=".providers-", suffix=".tmp"
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(store, handle, indent=2, ensure_ascii=False)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, path)
    finally:
        if os.path.exists(tmp_path):
            try:
                os.remove(tmp_path)
            except OSError:
                pass


def _public(provider):
    return {
        "id": provider.get("id"),
        "name": provider.get("name"),
        "base_url": provider.get("base_url"),
        "model": provider.get("model"),
        "enabled": bool(provider.get("enabled", True)),
        "is_default": bool(provider.get("is_default", False)),
        "has_key": bool(provider.get("api_key")),
        "api_key": masked_key(provider),
        "api_key_last4": provider.get("api_key_last4") or "",
    }


def list_providers():
    return [_public(provider) for provider in _load()["providers"]]


def _find(store, provider_id):
    return next(
        (
            provider
            for provider in store["providers"]
            if provider.get("id") == provider_id
        ),
        None,
    )


def _validate_url(value):
    value = str(value or "").strip().rstrip("/")
    if not value:
        raise SettingsError("base_url is required")

    parsed = urlparse(value)
    if parsed.username or parsed.password:
        raise SettingsError("base_url must not contain credentials")
    if parsed.query or parsed.fragment:
        raise SettingsError("base_url must not contain a query or fragment")

    if parsed.scheme == "https" and parsed.hostname:
        return value
    if (
        parsed.scheme == "http"
        and parsed.hostname
        and parsed.hostname.lower() in LOCAL_HOSTS
    ):
        return value

    raise SettingsError(
        "base_url must start with https:// (http:// is allowed only for "
        "localhost)"
    )


def _clean_text(payload, key, label, required=True, limit=200):
    value = str(payload.get(key) or "").strip()
    if required and not value:
        raise SettingsError(f"{label} is required")
    if len(value) > limit:
        raise SettingsError(f"{label} must be {limit} characters or fewer")
    return value


def _make_default(store, provider_id):
    for provider in store["providers"]:
        provider["is_default"] = provider.get("id") == provider_id


def add_provider(payload):
    payload = payload or {}
    name = _clean_text(payload, "name", "name", limit=80)
    base_url = _validate_url(payload.get("base_url"))
    model = _clean_text(payload, "model", "model", limit=200)
    raw_key = str(payload.get("api_key") or "").strip()
    if not raw_key:
        raise SettingsError("api_key is required")
    if len(raw_key) > 4096:
        raise SettingsError("api_key is too long")

    token = encrypt_key(raw_key)

    with state_module.locked():
        store = _load()
        if any(
            provider.get("name", "").lower() == name.lower()
            for provider in store["providers"]
        ):
            raise SettingsError("a provider with that name already exists")

        provider = {
            "id": uuid.uuid4().hex[:12],
            "name": name,
            "base_url": base_url,
            "api_key": token,
            "api_key_last4": raw_key[-4:],
            "model": model,
            "enabled": bool(payload.get("enabled", True)),
            "is_default": bool(payload.get("is_default")) or not store["providers"],
            "created_at": _now(),
            "updated_at": _now(),
        }
        store["providers"].append(provider)
        if provider["is_default"]:
            _make_default(store, provider["id"])
        _save(store)

    return _public(provider)


def update_provider(provider_id, payload):
    payload = payload or {}

    with state_module.locked():
        store = _load()
        provider = _find(store, provider_id)
        if provider is None:
            raise SettingsError("provider not found")

        if "name" in payload:
            name = _clean_text(payload, "name", "name", limit=80)
            if any(
                other.get("id") != provider_id
                and other.get("name", "").lower() == name.lower()
                for other in store["providers"]
            ):
                raise SettingsError("a provider with that name already exists")
            provider["name"] = name

        if "base_url" in payload:
            provider["base_url"] = _validate_url(payload.get("base_url"))

        if "model" in payload:
            provider["model"] = _clean_text(
                payload, "model", "model", limit=200
            )

        # An empty api_key means "keep the existing key".
        raw_key = str(payload.get("api_key") or "").strip()
        if raw_key:
            if len(raw_key) > 4096:
                raise SettingsError("api_key is too long")
            provider["api_key"] = encrypt_key(raw_key)
            provider["api_key_last4"] = raw_key[-4:]
            provider["updated_at"] = _now()

        if "enabled" in payload:
            provider["enabled"] = bool(payload.get("enabled"))

        if payload.get("is_default") is True:
            _make_default(store, provider_id)

        _save(store)

    return _public(provider)


def delete_provider(provider_id):
    with state_module.locked():
        store = _load()
        provider = _find(store, provider_id)
        if provider is None:
            raise SettingsError("provider not found")

        was_default = bool(provider.get("is_default"))
        store["providers"] = [
            item
            for item in store["providers"]
            if item.get("id") != provider_id
        ]

        if was_default and store["providers"]:
            replacement = next(
                (
                    item
                    for item in store["providers"]
                    if item.get("enabled") and item.get("api_key")
                ),
                store["providers"][0],
            )
            _make_default(store, replacement["id"])

        _save(store)
    return {"deleted": provider_id}


def get_provider(provider_id):
    provider = _find(_load(), provider_id)
    if provider is None:
        raise SettingsError("provider not found")
    return provider


def default_provider():
    """Return the default enabled provider with a stored key, or None."""
    for provider in _load()["providers"]:
        if (
            provider.get("is_default")
            and provider.get("enabled")
            and provider.get("api_key")
        ):
            return provider
    return None


def mode_info():
    provider = default_provider()
    if provider:
        return {
            "mode": "live",
            "provider_id": provider.get("id"),
            "provider": provider.get("name"),
            "model": provider.get("model"),
        }
    return {
        "mode": "mock",
        "reason": "No enabled provider with an API key is set as the default.",
    }
